function [xl,zl] = loop_profile(p)
%LOOP_PROFILE Points along the loop track in the x-z plane, for drawing.
%   Quarter circle up to vertical, a vertical wall of height Lv, a second
%   quarter circle to inverted, and a straight inverted segment of length Lt.

    th1 = linspace(0,pi/2,30);
    th2 = linspace(pi/2,pi,30);
    xl = [p.loop.x0 + p.loop.R*sin(th1), ...
          p.loop.x0 + p.loop.R*[1, 1], ...
          p.loop.x0 + p.loop.R*sin(th2), ...
          p.loop.x0 - p.loop.Lt];
    zl = [p.loop.R - p.loop.R*cos(th1), ...
          p.loop.R, p.loop.R + p.loop.Lv, ...
          p.loop.R + p.loop.Lv - p.loop.R*cos(th2), ...
          2*p.loop.R + p.loop.Lv];
end
